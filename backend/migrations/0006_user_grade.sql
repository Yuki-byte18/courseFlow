-- ============================================================================
-- 0006_user_grade.sql —— 学生年级
--
-- 起因：rounds.allow_grade 这个字段建了却从没被用上 ——
-- 选课校验里没有年级判断，把轮次配成"只开放大三"等于没配。
-- 留着不用的字段比删掉更糟：答辩时会被问。
--
-- 年级取值：
--   0  未设置（不参与限制）
--   1  大一  2 大二  3 大三  4 大四  5 大五/延毕
--
-- 为什么默认 0 而不是必填：已有账号重新补数据成本高，
-- 而"未设置"必须**不拦截**选课，否则一升级就把所有人挡在门外。
-- ============================================================================

-- +goose Up

ALTER TABLE users
    ADD COLUMN grade TINYINT UNSIGNED NOT NULL DEFAULT 0
        COMMENT '年级：0=未设置，1-5=大一..大五' AFTER status;

-- +goose Down

ALTER TABLE users DROP COLUMN grade;
